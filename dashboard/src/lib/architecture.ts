// Карта архітектури для сторінки /architecture: сам Mermaid-код і опис кожного
// блока. Модуль свідомо без server-only — його імпортує і клієнтський компонент
// діаграми, і серверний екшен, який віддає вміст файлів у поп-ап.

export interface ArchNode {
  title: string;
  // Один-два абзаци простою мовою: що робить блок і чому він саме такий.
  summary: string;
  // Файл у репозиторії, вміст якого показуємо в поп-апі. Має лежати всередині
  // ALLOWED_ROOTS (agents/prompts, agents/criteria, agents/catalogs, shared) —
  // інакше серверний екшен відмовиться його читати.
  doc?: string;
  // Файл, який варто згадати в поп-апі, але який недосяжний для читача
  // конфігурації (скрипти, плісти, код дашборда).
  ref?: string;
}

export interface ArchDiagram {
  id: string;
  title: string;
  caption: string;
  source: string;
}

